/* oncOS board maps inside the Evidence view.

   A sheet listed in MAPS gets a ruled Trials | Map tab pair above its trial
   table. Map draws that sheet's board map in place of the table, with the
   sidebar, masthead and theme unchanged. The location is the view's own
   /evidence/?group=<sheet> with the anchor #map, so back, forward, reload and
   shared links work through the shell's location contract.

   The Evidence view and the shell are generated by the Mac kit, so nothing here
   edits them. This file must load in <head>, before the shell boots: it wraps
   window.oncosView.navigation as the view sets it, so that the shell's first
   navigation.open() already understands #map.

   Each map lives in /maps/<id>/: sheet.html (the drawing) and trials.js
   (window.oncosMapData[<id>] = {map:{w,h,links,braces}, T:{cards}}).
   A new map = a new folder + one line in MAPS. */
(function(){
  var MAPS = {
    'Advanced NSCLC': 'nsclc',
    'Advanced Prostate': 'prostate'
  };
  var ANCHOR = 'map';
  var has = function(sheet){ return !!sheet && Object.prototype.hasOwnProperty.call(MAPS, sheet); };

  var view = null;        // the active window.oncosView
  var mapSheet = null;    // sheet whose map is showing, or null for the trial table
  var loaded = {};        // id -> Promise of sheet markup
  var drawn = null;       // id currently drawn in the pane
  var actual = false;
  try { actual = localStorage.getItem('oncos-map-actual') === '1'; } catch(e){}

  var css = document.createElement('link');
  css.rel = 'stylesheet'; css.href = '/maps/map.css';
  document.head.appendChild(css);

  /* ---- hook the Evidence view's navigation ---- */
  function wrapNav(n){
    return {
      read: function(){
        var t = n.read();
        if (mapSheet && t.group === mapSheet && !t.record) t.anchor = ANCHOR;
        else if (mapSheet) { mapSheet = null; schedule(); }
        return t;
      },
      open: function(target){
        var m = !!target && target.anchor === ANCHOR && has(target.group) && !target.record;
        var t = target;
        if (target && target.anchor === ANCHOR) { t = {}; for (var k in target) if (k !== 'anchor') t[k] = target[k]; }
        mapSheet = m ? target.group : null;
        sync();
        var ok = n.open(t);
        if (!ok && mapSheet) { mapSheet = null; sync(); }
        return ok;
      }
    };
  }
  function hookView(v){
    var nav;
    Object.defineProperty(v, 'navigation', {configurable:true, enumerable:true,
      get: function(){ return nav; },
      set: function(n){ nav = n && n.read && n.open ? wrapNav(n) : n; }});
  }
  var cur = window.oncosView;
  Object.defineProperty(window, 'oncosView', {configurable:true, enumerable:true,
    get: function(){ return cur; },
    set: function(v){
      cur = v;
      if (v && v.name === 'evidence') { view = v; mapSheet = null; drawn = null; hookView(v); }
    }});

  // Back and forward: decide from the entry's own URL before the shell restores it.
  window.addEventListener('popstate', function(){
    var u = new URL(location.href), g = u.searchParams.get('group');
    mapSheet = /^\/evidence\/?$/.test(u.pathname) && u.hash === '#' + ANCHOR && has(g) ? g : null;
    sync();
  }, true);

  // A sheet chosen in the sidebar, or All trials, opens its trial table.
  document.addEventListener('click', function(e){
    if (mapSheet && e.target.closest && e.target.closest('.sheets button, #showall')) { mapSheet = null; sync(); }
  }, true);

  /* ---- tabs and pane ---- */
  function activeSheet(){
    var b = document.querySelector('.sheets button.active');
    return b ? (b.dataset.sheet || b.textContent.trim()) : null;
  }
  function inEvidence(){ return document.documentElement.getAttribute('data-view') === 'evidence' && view && window.oncosView === view; }

  function show(on){
    var sheet = activeSheet();
    if (!has(sheet) || !view || !view.navigation) return;
    if (on === (mapSheet === sheet)) return;
    closeCard();
    mapSheet = on ? sheet : null;
    var url = window.oncosLocations.href('evidence', view.navigation.read(), location.origin);
    history.pushState({v:'evidence'}, '', url);
    sync();
    window.scrollTo(0, 0);
    var pane = document.getElementById('map');
    if (on && pane) { pane.tabIndex = -1; pane.focus({preventScroll:true}); }
  }

  function bar(top){
    var el = top.querySelector('.om-bar');
    if (el) return el;
    el = document.createElement('div');
    el.className = 'om-bar';
    el.innerHTML = '<div class="wl-tabs" role="tablist" aria-label="Sheet view">' +
      '<button type="button" class="wl-tab" role="tab" data-om="trials">Trials</button>' +
      '<button type="button" class="wl-tab" role="tab" data-om="map">Map</button></div>' +
      '<button type="button" class="om-zoom" aria-pressed="false"><span class="bx"></span>Actual size</button>';
    el.addEventListener('click', function(e){
      var b = e.target.closest('button'); if (!b) return;
      if (b.dataset.om) show(b.dataset.om === 'map');
      else if (b.classList.contains('om-zoom')) {
        actual = !actual;
        try { localStorage.setItem('oncos-map-actual', actual ? '1' : '0'); } catch(err){}
        layout();
      }
    });
    top.appendChild(el);
    return el;
  }

  function sync(){
    var top = document.querySelector('.viewfrag .topbar');
    var results = document.getElementById('results');
    if (!top || !results || !inEvidence()) return;
    var sheet = activeSheet();
    var mapped = has(sheet);
    var el = top.querySelector('.om-bar');
    if (!mapped) {
      if (el) el.remove();
      setPane(results, null);
      return;
    }
    el = bar(top);
    // mapSheet can name the sheet a back or forward step is about to restore.
    var on = mapSheet === sheet;
    el.classList.toggle('on', on);
    el.querySelectorAll('.wl-tab').forEach(function(b){ b.setAttribute('aria-selected', String((b.dataset.om === 'map') === on)); });
    el.querySelector('.om-zoom').setAttribute('aria-pressed', String(actual));
    setPane(results, on ? MAPS[mapSheet] : null);
  }

  function setPane(results, id){
    var pane = document.getElementById('map');
    if (!id) {
      results.style.removeProperty('display');
      if (pane) pane.hidden = true;
      closeCard();
      return;
    }
    if (!pane) {
      pane = document.createElement('section');
      pane.id = 'map';
      pane.setAttribute('aria-label', 'Board map');
      results.parentNode.insertBefore(pane, results.nextSibling);
    }
    results.style.setProperty('display', 'none');
    pane.hidden = false;
    if (drawn === id && pane.querySelector('.om-sheet')) { layout(); return; }
    drawn = id;
    pane.innerHTML = '';
    load(id).then(function(html){
      if (drawn !== id || !document.body.contains(pane)) return;
      draw(pane, id, html);
    }, function(){
      if (drawn === id) { drawn = null; pane.textContent = 'The map did not load.'; }
    });
  }

  function load(id){
    if (loaded[id]) return loaded[id];
    var data = new Promise(function(resolve, reject){
      if (window.oncosMapData && window.oncosMapData[id]) return resolve();
      var s = document.createElement('script');
      s.src = '/maps/' + id + '/trials.js';
      s.onload = function(){ window.oncosMapData && window.oncosMapData[id] ? resolve() : reject(); };
      s.onerror = reject;
      document.head.appendChild(s);
    });
    var html = fetch('/maps/' + id + '/sheet.html', {credentials:'same-origin'}).then(function(r){
      if (!r.ok) throw new Error(r.status); return r.text();
    });
    loaded[id] = Promise.all([html, data]).then(function(v){ return v[0]; });
    loaded[id].catch(function(){ delete loaded[id]; });
    return loaded[id];
  }

  /* ---- drawing ---- */
  var cfg = null, T = {}, wrap = null, sheetEl = null;
  function draw(pane, id, html){
    var d = window.oncosMapData[id];
    cfg = d.map || {}; T = d.T || {};
    pane.innerHTML = '<div class="om-wrap"><div class="om-sheet">' + html + '</div></div>';
    wrap = pane.firstChild; sheetEl = wrap.firstChild;
    sheetEl.style.width = (cfg.w || 1600) + 'px';
    sheetEl.style.height = (cfg.h || 1550) + 'px';
    sheetEl.querySelectorAll('t').forEach(function(el){
      var b = document.createElement('button');
      b.className = 'trial'; b.type = 'button'; b.dataset.k = el.getAttribute('k'); b.textContent = el.textContent;
      el.replaceWith(b);
    });
    layout();
    if (document.fonts && document.fonts.ready) document.fonts.ready.then(layout);
  }
  function q(id){ return sheetEl && sheetEl.querySelector('[id="' + id + '"]'); }
  function pos(el){
    var x = 0, y = 0, e = el;
    while (e && e !== sheetEl) { x += e.offsetLeft; y += e.offsetTop; e = e.offsetParent; }
    return {x:x, y:y, r:x + el.offsetWidth, b:y + el.offsetHeight, cx:x + el.offsetWidth/2, cy:y + el.offsetHeight/2};
  }
  function side(p, s){
    if (s === 'l') return [p.x, p.cy];
    if (s === 't') return [p.cx, p.y];
    if (s === 'b') return [p.cx, p.b];
    return [p.r, p.cy];
  }
  function bracePath(x, y1, y2, d){
    var m = (y1 + y2) / 2, k = 6;
    return 'M'+x+' '+y1+' Q'+(x+d)+' '+y1+' '+(x+d)+' '+(y1+k)+' L'+(x+d)+' '+(m-k)+' Q'+(x+d)+' '+m+' '+(x+2*d)+' '+m+' Q'+(x+d)+' '+m+' '+(x+d)+' '+(m+k)+' L'+(x+d)+' '+(y2-k)+' Q'+(x+d)+' '+y2+' '+x+' '+y2;
  }
  function layout(){
    if (!sheetEl || !document.body.contains(sheetEl) || !sheetEl.offsetParent) return;
    var W = cfg.w || 1600, H = cfg.h || 1550;
    var s = actual ? 1 : Math.min(1, wrap.clientWidth / W);
    sheetEl.style.transform = 'scale(' + s + ')';
    wrap.style.height = actual ? 'auto' : Math.ceil(H * s) + 'px';
    wrap.classList.toggle('actual', actual);
    var out = '';
    (cfg.links || []).forEach(function(L){
      var a = q(L.from), b = q(L.to); if (!a || !b) return;
      var p1 = side(pos(a), L.fromSide || 'r'), p2 = side(pos(b), L.toSide || 'l');
      out += '<line x1="'+(p1[0]+(L.dx1||0))+'" y1="'+(p1[1]+(L.dy1||0))+'" x2="'+(p2[0]+(L.dx2||0))+'" y2="'+(p2[1]+(L.dy2||0))+'"/>';
    });
    var wires = sheetEl.querySelector('.om-wires'); if (wires) wires.innerHTML = out;
    (cfg.braces || []).forEach(function(B){
      var t = q(B.top), b = q(B.bottom), el = q(B.id); if (!t || !b || !el) return;
      var y1 = pos(t).y, y2 = pos(b).b, h = y2 - y1 + 4;
      el.style.left = B.x + 'px'; el.style.top = (y1 - 2) + 'px';
      el.innerHTML = '<svg width="26" height="'+h+'" viewBox="0 0 26 '+h+'"><path d="'+bracePath(2, 2, h-2, 9)+'"/></svg>';
      var n = B.note && q(B.note); if (n) n.style.top = ((y1 + y2)/2 - n.offsetHeight/2) + 'px';
    });
  }
  window.addEventListener('resize', function(){ if (mapSheet) layout(); });

  /* ---- trial card ---- */
  var card = null, cardKey = null;
  function esc(s){ return String(s == null ? '' : s).replace(/[&<>"]/g, function(c){ return {'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]; }); }
  function makeCard(){
    card = document.createElement('aside');
    card.id = 'om-card'; card.setAttribute('aria-live', 'polite');
    card.innerHTML = '<div class="hd"><span class="t"></span><button type="button" aria-label="Close">×</button></div><div class="cb"><table></table></div><a class="ev" hidden>Open the Evidence row</a>';
    card.querySelector('.hd button').addEventListener('click', closeCard);
    document.body.appendChild(card);
  }
  function openCard(k, btn){
    var d = T[k]; if (!d) return;
    if (!card) makeCard();
    sheetEl.querySelectorAll('button.trial.on').forEach(function(x){ x.classList.remove('on'); });
    btn.classList.add('on'); cardKey = k;
    card.querySelector('.t').textContent = d.n;
    var rows = [['Control arm', d.ctl], ['Patients', d.pts], ['Primary endpoint', d.ep], ['Result', d.res], ['OS', d.os]];
    var h = rows.filter(function(r){ return r[1]; }).map(function(r){ return '<tr><th>' + r[0] + '</th><td>' + esc(r[1]) + '</td></tr>'; }).join('');
    h += '<tr><th>Reference</th><td>' + (d.ref || []).map(function(r){ return esc(r[0]) + ' · <a href="' + esc(r[1]) + '" target="_blank" rel="noopener">' + esc(r[2]) + '</a>'; }).join('<br>') + '</td></tr>';
    card.querySelector('table').innerHTML = h;
    var ev = card.querySelector('.ev');
    if (d.ev) { ev.hidden = false; ev.setAttribute('href', '/evidence/#' + d.ev); }
    else { ev.hidden = true; ev.removeAttribute('href'); }
    card.classList.add('open');
  }
  function closeCard(){
    if (card) card.classList.remove('open');
    cardKey = null;
    if (sheetEl) sheetEl.querySelectorAll('button.trial.on').forEach(function(x){ x.classList.remove('on'); });
  }
  document.addEventListener('click', function(e){
    var tb = e.target.closest && e.target.closest('#map button.trial');
    if (tb) {
      if (cardKey === tb.dataset.k && card && card.classList.contains('open')) closeCard();
      else openCard(tb.dataset.k, tb);
      return;
    }
    if (e.target.closest && e.target.closest('#om-card .ev')) closeCard();
  });
  document.addEventListener('keydown', function(e){ if (e.key === 'Escape' && cardKey) closeCard(); });

  /* ---- follow the view as it re-renders ---- */
  var t = null;
  function schedule(){ if (t) return; t = setTimeout(function(){ t = null; sync(); }, 30); }
  function observe(){
    new MutationObserver(function(list){
      for (var i = 0; i < list.length; i++) {
        var n = list[i].target;
        if (n.nodeType === 1 && (n.id === 'map' || (n.closest && n.closest('#map, #om-card')))) continue;
        return schedule();
      }
    }).observe(document.documentElement, {childList:true, subtree:true, attributes:true, attributeFilter:['class', 'data-view']});
    schedule();
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', observe); else observe();
})();
